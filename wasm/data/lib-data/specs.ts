export function specById(id: SpecId): SpecDef {
  const found = SPECS.find((entry) => entry.id === id);
  if (!found) {
    throw new Error(`unknown spec ${id}`);
  }
  return found;
}

export function specsForClass(wowClass: WowClass, roles: Role[]): SpecDef[] {
  return SPECS.filter(
    (entry) =>
      entry.wowClass === wowClass &&
      roles.includes(entry.role) &&
      !entry.needsOverride,
  );
}

export function dpsSpecs(): SpecDef[] {
  return SPECS.filter((entry) => entry.role === "dps");
}

export function healTankSpecs(): SpecDef[] {
  return SPECS.filter((entry) => entry.role === "heal" || entry.role === "tank");
}
